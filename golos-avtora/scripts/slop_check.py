WORD = re.compile(r"[А-Яа-яЁёA-Za-z\-]+")
TRIAD = re.compile(r"\b([а-яё]{3,}),\s+([а-яё]{3,})\s+и\s+([а-яё]{3,})\b", re.I)
SENT = re.compile(r"[^.!?\n]+[.!?]?")


def count_words(t):
    return len(WORD.findall(t))


def check(text):
    hits = []
    lines = text.split("\n")
    for wid, cat, rx, w, fix in P:
        for m in rx.finditer(text):
            ln = text.count("\n", 0, m.start()) + 1
            frag = m.group(0).strip().replace("\n", " ")[:90]
            hits.append({"id": wid, "cat": cat, "w": w, "line": ln, "frag": frag, "fix": fix})
    # правило трёх: тройки «X, Y и Z»
    for m in TRIAD.finditer(text):
        ln = text.count("\n", 0, m.start()) + 1
        hits.append({"id": "правило трёх", "cat": "2. Язык и грамматика", "w": 0.5, "line": ln,
                     "frag": m.group(0), "fix": "Тройка «X, Y и Z». Одна на текст нормально; если их много, оставь 1–2 пункта или конкретику."})
    nw = max(count_words(text), 1)
    # метрики уровня текста
    prose = " ".join(l.strip() for l in text.split("\n") if l.strip() and not re.match(r"^\s*([✅•\-–\*]|\d+[.)])", l))
    sents = [s.strip() for s in re.findall(r"[^.!?…]+[.!?…]*", prose) if count_words(s) > 0]
    lens = [count_words(s) for s in sents]
    bold = len(re.findall(r"\*\*[^*]+\*\*", text))
    digits = len(re.findall(r"\d+", text))
    caps_names = len(re.findall(r"(?<=[а-яё,] )[А-ЯЁA-Z][а-яёa-z]+", text))
    one_line_paras = sum(1 for p in re.split(r"\n\s*\n", text) if p.strip() and "\n" not in p.strip() and count_words(p) < 15)
    paras = max(len([p for p in re.split(r"\n\s*\n", text) if p.strip()]), 1)
    stats = {
        "слов": nw,
        "предложений": len(sents),
        "средняя длина предложения": round(sum(lens) / len(lens), 1) if lens else 0,
        "разброс длины (ст. откл.)": round((sum((x - sum(lens) / len(lens)) ** 2 for x in lens) / len(lens)) ** .5, 1) if lens else 0,
        "жирных выделений на 100 слов": round(100 * bold / nw, 2),
        "длинных тире на 100 слов": round(100 * len(re.findall(r"\s—\s", text)) / nw, 2),
        "конкретика (цифры+имена) на 100 слов": round(100 * (digits + caps_names) / nw, 2),
        "доля однострочных абзацев": round(one_line_paras / paras, 2),
    }
    score = round(100 * sum(h["w"] for h in hits) / nw, 2)
    flags = []
    if stats["разброс длины (ст. откл.)"] < 3 and len(sents) >= 6:
        flags.append("Монотонный ритм: все предложения одной длины. Добавь короткие (1–4 слова) и одно длинное.")
    if stats["конкретика (цифры+имена) на 100 слов"] < 1.5 and nw > 80:
        flags.append("Мало конкретики: нет цифр, имён, дат, деталей. Общие слова на месте фактов — главный признак слопа по Википедии.")
    if stats["доля однострочных абзацев"] > 0.7 and paras >= 5:
        flags.append("Рубленый текст: почти все абзацы по одной строке. Соедини мысли связками.")
    return {"score_per_100_words": score, "hits": hits, "stats": stats, "flags": flags}


def verdict(score):
    if score < 1.5:
        return "чисто: живой текст"
    if score < 4:
        return "есть отдельные штампы: поправь отмеченное"
    if score < 8:
        return "заметно ИИ-шно: перепиши отмеченные куски"
    return "нейрослоп: переписать с нуля своими словами"


def compare_profile(stats, prof):
    """Сравнение черновика с личной нормой автора (profile.json из style_analyzer)."""
    out = []
    own = prof.get("own_voice") or {}
    if not own:
        return out
    # both=True: отклонение в обе стороны плохо; иначе плохо только превышение нормы
    pairs = [("средняя длина предложения", "слов в предложении", 0.3, True),
             ("жирных выделений на 100 слов", "жирный на 100 слов", 0.6, False),
             ("длинных тире на 100 слов", "тире — на 100 слов", 0.6, False)]
    for k_draft, k_own, tol, both in pairs:
        a, b = stats.get(k_draft), own.get(k_own)
        if a is None or b is None:
            continue
        if b == 0 and a > 0.3:
            out.append(f"{k_draft}: в черновике {a}, у автора ≈0. Убрать.")
        elif b and (a - b) / b > tol:
            out.append(f"{k_draft}: в черновике {a}, у автора {b}. Выше нормы, сократить.")
        elif b and both and (b - a) / b > tol:
            out.append(f"{k_draft}: в черновике {a}, у автора {b}. Ниже нормы, подогнать.")
    return out


def main():
    import signal
    signal.signal(signal.SIGPIPE, signal.SIG_DFL)
    ap = argparse.ArgumentParser()
    ap.add_argument("file")
    ap.add_argument("--profile")
    ap.add_argument("--json", action="store_true")
    a = ap.parse_args()
    text = open(a.file, encoding="utf-8").read()
    r = check(text)
    if a.profile:
        r["vs_author"] = compare_profile(r["stats"], json.load(open(a.profile, encoding="utf-8")))
    if a.json:
        print(json.dumps(r, ensure_ascii=False, indent=1)); return
    print(f"Индекс нейрослопа: {r['score_per_100_words']} на 100 слов: {verdict(r['score_per_100_words'])}\n")
    by = defaultdict(list)
    for h in r["hits"]:
        by[h["cat"]].append(h)
    for cat in sorted(by):
        print(f"## {cat}")
        for h in by[cat]:
            print(f"  стр.{h['line']:>3} [{h['id']}] «{h['frag']}»")
        seen = []
        for h in by[cat]:
            if h["fix"] not in seen:
                seen.append(h["fix"]); print(f"     → {h['fix']}")
        print()
    print("## Метрики текста")
    for k, v in r["stats"].items():
        print(f"  {k}: {v}")
    for f in r["flags"]:
        print(f"  ⚠ {f}")
    for f in r.get("vs_author", []):
        print(f"  ≠ {f}")


if __name__ == "__main__":
    main()
